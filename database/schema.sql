CREATE DATABASE IF NOT EXISTS sistema_bilhetes
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE sistema_bilhetes;

CREATE TABLE IF NOT EXISTS utilizadores (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  email VARCHAR(180) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  perfil ENUM('PASSAGEIRO', 'ADMIN') NOT NULL DEFAULT 'PASSAGEIRO',
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS autocarros (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  matricula VARCHAR(30) NOT NULL UNIQUE,
  modelo VARCHAR(100) NOT NULL,
  capacidade SMALLINT UNSIGNED NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS rotas (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  origem VARCHAR(100) NOT NULL,
  destino VARCHAR(100) NOT NULL,
  distancia_km DECIMAL(8, 2) NULL,
  activa BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS viagens (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  rota_id BIGINT UNSIGNED NOT NULL,
  autocarro_id BIGINT UNSIGNED NOT NULL,
  partida_em DATETIME NOT NULL,
  chegada_prevista_em DATETIME NULL,
  preco DECIMAL(10, 2) NOT NULL,
  estado ENUM('AGENDADA', 'EM_CURSO', 'CONCLUIDA', 'CANCELADA') NOT NULL DEFAULT 'AGENDADA',
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_viagem_rota FOREIGN KEY (rota_id) REFERENCES rotas(id),
  CONSTRAINT fk_viagem_autocarro FOREIGN KEY (autocarro_id) REFERENCES autocarros(id)
);

CREATE TABLE IF NOT EXISTS assentos (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  autocarro_id BIGINT UNSIGNED NOT NULL,
  numero VARCHAR(10) NOT NULL,
  CONSTRAINT uq_assento_autocarro UNIQUE (autocarro_id, numero),
  CONSTRAINT fk_assento_autocarro FOREIGN KEY (autocarro_id) REFERENCES autocarros(id)
);

CREATE TABLE IF NOT EXISTS bilhetes (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  codigo VARCHAR(40) NOT NULL UNIQUE,
  utilizador_id BIGINT UNSIGNED NULL,
  viagem_id BIGINT UNSIGNED NOT NULL,
  assento_id BIGINT UNSIGNED NOT NULL,
  nome_passageiro VARCHAR(120) NOT NULL,
  preco DECIMAL(10, 2) NOT NULL,
  estado ENUM('RESERVADO', 'EMITIDO', 'CANCELADO') NOT NULL DEFAULT 'RESERVADO',
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_bilhete_utilizador FOREIGN KEY (utilizador_id) REFERENCES utilizadores(id),
  CONSTRAINT fk_bilhete_viagem FOREIGN KEY (viagem_id) REFERENCES viagens(id),
  CONSTRAINT fk_bilhete_assento FOREIGN KEY (assento_id) REFERENCES assentos(id)
);

CREATE TABLE IF NOT EXISTS pagamentos (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  bilhete_id BIGINT UNSIGNED NOT NULL,
  metodo ENUM('MPESA', 'EMOLA', 'CARTAO') NOT NULL,
  referencia VARCHAR(60) NOT NULL UNIQUE,
  valor DECIMAL(10, 2) NOT NULL,
  estado ENUM('PENDENTE', 'APROVADO', 'REJEITADO') NOT NULL DEFAULT 'PENDENTE',
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_pagamento_bilhete FOREIGN KEY (bilhete_id) REFERENCES bilhetes(id)
);
