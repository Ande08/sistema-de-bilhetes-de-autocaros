import { Router } from 'express';
import { actualizarEmpresa, actualizarEmpresaGestao, actualizarUtilizador, actualizarViagem, criarAutocarro, criarEmpresa, criarRota, criarUtilizador, criarViagem, decidirCadastroEmpresa, definirEstadoAutocarro, definirEstadoEmpresa, definirEstadoPassageiro, definirEstadoRota, eliminarEmpresa, eliminarUtilizador, listarEmpresasGestao, obterEmpresa, obterEmpresaGestao, obterPainel, redefinirSenhaUtilizador } from '../controllers/gestao.controller.js';
import { exigirAutenticacao } from '../middlewares/autenticacao.middleware.js';
import { exigirAdministradorEmpresa, exigirAdministradorEmpresaOuPlataforma, exigirAdministradorPlataforma } from '../middlewares/autorizacao.middleware.js';
import { auditarOperacaoAdministrativa } from '../middlewares/auditoria.middleware.js';
import { iniciarWhatsApp, obterEstadoWhatsApp, repetirEnvio } from '../controllers/whatsapp.controller.js';
import { guardarConfiguracao, obterConfiguracao, obterModelos, testarLigacao } from '../controllers/configuracao-ia.controller.js';
import { enviarAviso } from '../controllers/aviso-viagem.controller.js';
import { actualizarCupao, criarCupao, definirEstadoCupao, listarCupoes } from '../controllers/cupao.controller.js';

const router = Router();
router.use(exigirAutenticacao);
router.use(auditarOperacaoAdministrativa);
router.get('/painel', exigirAdministradorEmpresaOuPlataforma, obterPainel);
router.get('/empresas', exigirAdministradorPlataforma, listarEmpresasGestao);
router.post('/empresas', exigirAdministradorPlataforma, criarEmpresa);
router.get('/empresas/:id', exigirAdministradorPlataforma, obterEmpresaGestao);
router.put('/empresas/:id', exigirAdministradorPlataforma, actualizarEmpresaGestao);
router.patch('/empresas/:id/aprovacao', exigirAdministradorPlataforma, decidirCadastroEmpresa);
router.patch('/empresas/:id/estado', exigirAdministradorPlataforma, definirEstadoEmpresa);
router.delete('/empresas/:id', exigirAdministradorPlataforma, eliminarEmpresa);
router.get('/empresa', exigirAdministradorEmpresa, obterEmpresa);
router.put('/empresa', exigirAdministradorEmpresa, actualizarEmpresa);
router.get('/whatsapp/estado', exigirAdministradorPlataforma, obterEstadoWhatsApp);
router.post('/whatsapp/iniciar', exigirAdministradorPlataforma, iniciarWhatsApp);
router.post('/whatsapp/envios/:id/repetir', exigirAdministradorPlataforma, repetirEnvio);
router.get('/ia/configuracao', exigirAdministradorPlataforma, obterConfiguracao);
router.put('/ia/configuracao', exigirAdministradorPlataforma, guardarConfiguracao);
router.get('/ia/modelos', exigirAdministradorPlataforma, obterModelos);
router.post('/ia/testar', exigirAdministradorPlataforma, testarLigacao);
router.post('/autocarros', exigirAdministradorEmpresa, criarAutocarro);
router.patch('/autocarros/:id/estado', exigirAdministradorEmpresa, definirEstadoAutocarro);
router.post('/rotas', exigirAdministradorEmpresa, criarRota);
router.patch('/rotas/:id/estado', exigirAdministradorEmpresa, definirEstadoRota);
router.post('/viagens', exigirAdministradorEmpresa, criarViagem);
router.put('/viagens/:id', exigirAdministradorEmpresa, actualizarViagem);
router.post('/viagens/:id/avisos-whatsapp', exigirAdministradorEmpresa, enviarAviso);
router.get('/cupons', exigirAdministradorEmpresa, listarCupoes);
router.post('/cupons', exigirAdministradorEmpresa, criarCupao);
router.put('/cupons/:id', exigirAdministradorEmpresa, actualizarCupao);
router.patch('/cupons/:id/estado', exigirAdministradorEmpresa, definirEstadoCupao);
router.post('/utilizadores', exigirAdministradorEmpresaOuPlataforma, criarUtilizador);
router.put('/utilizadores/:id', exigirAdministradorEmpresaOuPlataforma, actualizarUtilizador);
router.put('/utilizadores/:id/palavra-passe', exigirAdministradorEmpresaOuPlataforma, redefinirSenhaUtilizador);
router.delete('/utilizadores/:id', exigirAdministradorEmpresaOuPlataforma, eliminarUtilizador);
router.patch('/utilizadores/:id/estado', exigirAdministradorEmpresaOuPlataforma, definirEstadoPassageiro);

export default router;
