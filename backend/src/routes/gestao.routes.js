import { Router } from 'express';
import { actualizarEmpresa, actualizarUtilizador, actualizarViagem, criarAutocarro, criarRota, criarUtilizador, criarViagem, definirEstadoAutocarro, definirEstadoPassageiro, definirEstadoRota, eliminarUtilizador, obterEmpresa, obterPainel, redefinirSenhaUtilizador } from '../controllers/gestao.controller.js';
import { exigirAutenticacao } from '../middlewares/autenticacao.middleware.js';
import { exigirAdministrador, exigirAdministradorEmpresaOuPlataforma } from '../middlewares/autorizacao.middleware.js';
import { auditarOperacaoAdministrativa } from '../middlewares/auditoria.middleware.js';
import { iniciarWhatsApp, obterEstadoWhatsApp, repetirEnvio } from '../controllers/whatsapp.controller.js';
import { guardarConfiguracao, obterConfiguracao, obterModelos, testarLigacao } from '../controllers/configuracao-ia.controller.js';
import { enviarAviso } from '../controllers/aviso-viagem.controller.js';

const router = Router();
router.use(exigirAutenticacao, exigirAdministradorEmpresaOuPlataforma);
router.use(auditarOperacaoAdministrativa);
router.get('/painel', obterPainel);
router.get('/empresa', obterEmpresa);
router.put('/empresa', actualizarEmpresa);
router.get('/whatsapp/estado', exigirAdministrador, obterEstadoWhatsApp);
router.post('/whatsapp/iniciar', exigirAdministrador, iniciarWhatsApp);
router.post('/whatsapp/envios/:id/repetir', exigirAdministrador, repetirEnvio);
router.get('/ia/configuracao', exigirAdministrador, obterConfiguracao);
router.put('/ia/configuracao', exigirAdministrador, guardarConfiguracao);
router.get('/ia/modelos', exigirAdministrador, obterModelos);
router.post('/ia/testar', exigirAdministrador, testarLigacao);
router.post('/autocarros', criarAutocarro);
router.patch('/autocarros/:id/estado', definirEstadoAutocarro);
router.post('/rotas', criarRota);
router.patch('/rotas/:id/estado', definirEstadoRota);
router.post('/viagens', criarViagem);
router.put('/viagens/:id', actualizarViagem);
router.post('/viagens/:id/avisos-whatsapp', enviarAviso);
router.post('/utilizadores', criarUtilizador);
router.put('/utilizadores/:id', actualizarUtilizador);
router.put('/utilizadores/:id/palavra-passe', redefinirSenhaUtilizador);
router.delete('/utilizadores/:id', eliminarUtilizador);
router.patch('/utilizadores/:id/estado', definirEstadoPassageiro);
router.patch('/passageiros/:id/estado', definirEstadoPassageiro);

export default router;
